import {readFileSync,writeFileSync,copyFileSync,mkdirSync,existsSync} from 'node:fs';
import {resolve,dirname,basename,relative,sep} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';

// A portable design demo: only checked-in, reviewed content enters this folder.
// No profile, browser storage, application run or service worker is involved.
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const output=resolve(root,'previews/mobile-ui');
const assetsDir=resolve(output,'assets');
const ids=['2024-0-1','2024-0-17','2024-1-6','2024-0-12'];
const readJSON=p=>JSON.parse(readFileSync(resolve(root,p),'utf8').replace(/^\uFEFF/,''));
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const bank=readJSON('src/bank.json');
const presentations=readJSON('src/question-presentations.json');
const manifest=[];
const copied=new Map();
mkdirSync(assetsDir,{recursive:true});

function include(source,name=basename(source)){
 const absolute=resolve(root,source);
 if(!absolute.startsWith(root+sep))throw Error('Source outside project: '+source);
 if(!existsSync(absolute))throw Error('Missing source: '+source);
 const target=resolve(assetsDir,name);
 if(!target.startsWith(assetsDir+sep))throw Error('Asset outside demo: '+name);
 const bytes=readFileSync(absolute);
 const digest=hash(bytes);
 if(copied.has(name)){
  if(copied.get(name)!==digest)throw Error('Asset filename collision: '+name);
  return 'assets/'+name;
 }
 copyFileSync(absolute,target);
 copied.set(name,digest);
 manifest.push({source:relative(root,absolute).split(sep).join('/'),path:'assets/'+name,bytes:bytes.length,sha256:digest});
 return 'assets/'+name;
}

include('public/fonts/NotoSansKR.ttf');
include('public/ui-v3/library.webp');
for(const state of ['idle','question','correct','sigh'])include('public/characters/runtime/'+state+'.webp');

const questions=ids.map(id=>{
 const q=bank.find(q=>q.id===id);
 if(!q?.verified)throw Error('Only reviewed questions can be copied: '+id);
 const p=structuredClone(q.presentation||presentations[id]);
 if(!p)throw Error('Reviewed display presentation required: '+id);
 if(p.options?.length!==4||q.answer<1||q.answer>4)throw Error('Invalid answer/options: '+id);
 for(const block of p.blocks){
  if(block.kind==='source')block.src=include('public/'+block.src.replace(/^\//,''));
 }
 const sources=(q.images||[]).map((src,index)=>({
  src:include('public/'+src.replace(/^\//,'')),
  label:`${q.year}년 ${q.subject} ${q.number}번 원문${q.images.length>1?' '+(index+1):''}`,
 }));
 return {id:q.id,year:q.year,subject:q.subject,number:q.number,answer:q.answer,explanation:q.explanation,distractors:q.distractors,presentation:p,sources};
});

const serialized=JSON.stringify(questions,null,2).replace(/</g,'\\u003c').replace(/\u2028/g,'\\u2028').replace(/\u2029/g,'\\u2029');
writeFileSync(resolve(output,'fixtures.js'),'// Generated by scripts/build-mobile-ui-fixtures.mjs. Reviewed demo data only.\nwindow.DEMO_QUESTIONS = '+serialized+';\n','utf8');
manifest.sort((a,b)=>a.path.localeCompare(b.path));
const provenance={
 version:1,
 generatedBy:'scripts/build-mobile-ui-fixtures.mjs',
 questionIds:ids,
 inputSources:['src/bank.json','src/question-presentations.json'].map(source=>({source,sha256:hash(readFileSync(resolve(root,source)))})),
 assets:manifest,
 bytes:manifest.reduce((sum,a)=>sum+a.bytes,0),
 runtime:{externalRequests:false,jsonFetch:false,modules:false,storage:false},
};
writeFileSync(resolve(output,'ASSETS.json'),JSON.stringify(provenance,null,2)+'\n','utf8');
console.log(`Prepared ${questions.length} reviewed questions, ${manifest.length} local assets, ${provenance.bytes.toLocaleString()} bytes.`);
